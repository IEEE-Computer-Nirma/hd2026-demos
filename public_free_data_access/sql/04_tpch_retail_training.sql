-- 2.5 Supplier performance – average delivery time
SELECT
    s.S_NAME,
    n.N_NAME AS NATION,
    COUNT(*) AS ITEMS_SHIPPED,
    ROUND(AVG(DATEDIFF('day', l.L_SHIPDATE, l.L_RECEIPTDATE)), 1) AS AVG_DELIVERY_DAYS
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM l
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.SUPPLIER s ON l.L_SUPPKEY = s.S_SUPPKEY
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION n ON s.S_NATIONKEY = n.N_NATIONKEY
WHERE l.L_RECEIPTDATE IS NOT NULL
GROUP BY s.S_NAME, n.N_NAME
ORDER BY ITEMS_SHIPPED DESC
LIMIT 20;

-- 2.6 Monthly order trends
