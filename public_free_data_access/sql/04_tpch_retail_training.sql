-- ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
-- LEVEL 2: INTERMEDIATE – JOINs and Aggregations
-- ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

-- 2.1 Revenue by nation (customer's nation)
SELECT
    n.N_NAME AS NATION,
    COUNT(DISTINCT o.O_ORDERKEY) AS ORDER_COUNT,
    ROUND(SUM(o.O_TOTALPRICE), 2) AS TOTAL_REVENUE
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS o
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER c ON o.O_CUSTKEY = c.C_CUSTKEY
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION n ON c.C_NATIONKEY = n.N_NATIONKEY
GROUP BY n.N_NAME
ORDER BY TOTAL_REVENUE DESC;

-- 2.2 Revenue by region
SELECT
    r.R_NAME AS REGION,
    COUNT(DISTINCT o.O_ORDERKEY) AS ORDER_COUNT,
    ROUND(SUM(o.O_TOTALPRICE), 2) AS TOTAL_REVENUE
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS o
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER c ON o.O_CUSTKEY = c.C_CUSTKEY
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION n ON c.C_NATIONKEY = n.N_NATIONKEY
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.REGION r ON n.N_REGIONKEY = r.R_REGIONKEY
GROUP BY r.R_NAME
ORDER BY TOTAL_REVENUE DESC;

-- 2.3 Top 20 customers by lifetime spend
SELECT
    c.C_NAME,
    n.N_NAME AS NATION,
    COUNT(o.O_ORDERKEY) AS ORDER_COUNT,
    ROUND(SUM(o.O_TOTALPRICE), 2) AS LIFETIME_SPEND
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS o
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER c ON o.O_CUSTKEY = c.C_CUSTKEY
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION n ON c.C_NATIONKEY = n.N_NATIONKEY
GROUP BY c.C_NAME, n.N_NAME
ORDER BY LIFETIME_SPEND DESC
LIMIT 20;

-- 2.4 Top parts by total quantity sold
SELECT
    p.P_NAME,
    p.P_TYPE,
    p.P_SIZE,
    SUM(l.L_QUANTITY) AS TOTAL_QTY,
    ROUND(SUM(l.L_EXTENDEDPRICE), 2) AS TOTAL_REVENUE
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM l
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.PART p ON l.L_PARTKEY = p.P_PARTKEY
GROUP BY p.P_NAME, p.P_TYPE, p.P_SIZE
